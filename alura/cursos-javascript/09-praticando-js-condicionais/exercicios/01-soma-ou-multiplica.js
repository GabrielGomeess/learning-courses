// IF/ELSE

// 1° - Definir um fluxo para somar ou multiplicar dois números usando if/else

const numA = 2;
const numB = 4;

const operacao = 'divisao';

if (operacao === 'soma') {
    console.log(numA + numB);
} else if (operacao === 'multiplicacao'){
    console.log(numA * numB);
} else {
    console.log('Operação Não Identificada!');
}




