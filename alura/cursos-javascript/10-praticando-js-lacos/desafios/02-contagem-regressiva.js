// Crie um programa que conte de 10 até 0
// e exiba a mensagem “Lançar!” ao final.

// preciso criar um for
// iniciando a contagem no 10
// o ponto de parada será o 0
// aqui será um decremento
// será imprimido a contagem um por um

for (let contagem = 10; contagem >= 0; contagem--) {
  console.log(contagem);
}

console.log("Lançar!");
